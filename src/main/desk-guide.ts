import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import type { Todo, WorkDesk } from './domain/types'
import { deskDir } from './projects/layout'

export const GUIDE_FILE = 'CLAUDE.md'
export const START = '<!-- workdesk:start - generated by WorkDesk, changes between these markers are overwritten -->'
export const END = '<!-- workdesk:end -->'
const OWN_HEADING = '## Your notes for this WorkDesk'
const OWN_HINT = 'Everything below the generated block stays as you write it.'

const todoLine = (t: Todo): string => {
  const ref = t.source?.ticketKey ?? t.source?.url
  return `- [${t.resolved ? 'x' : ' '}] ${t.title}${ref ? ` (${ref})` : ''}`
}

/** The part WorkDesk owns: what this WorkDesk is, and how it is handled. */
export function renderGuide(desk: WorkDesk, todos: readonly Todo[], dir: string): string {
  const mine = todos.filter((t) => t.deskId === desk.id)
  const lines = [START, `# WorkDesk: ${desk.name}`, '', `A WorkDesk, stage **${desk.stage}**. This file is kept up to date by WorkDesk.`, '']
  for (const r of desk.reviews ?? []) lines.push(`Reviewing ${r.owner}/${r.repo}#${r.number}: ${r.url}`)
  if ((desk.reviews ?? []).length > 0) lines.push('')
  lines.push('## Todos', '', ...(mine.length > 0 ? mine.map(todoLine) : ['None.']), '')
  lines.push('## Branches', '')
  if (desk.branches.length === 0) lines.push('None checked out yet.')
  for (const b of desk.branches) {
    lines.push(`- ${b.project}: \`${b.branch}\` in \`${relative(dir, b.path) || '.'}\`${b.base ? `, on top of \`${b.base}\` (a stack)` : ''}`)
  }
  lines.push(
    '',
    '## How this WorkDesk is handled',
    '',
    '- Every branch has its own git worktree inside this folder. Never switch branches in one; work in the worktree of the branch you need.',
    '- Never delete branches. Clearing a WorkDesk removes the worktrees, not the branches.',
    '- `.env` files come from WorkDesk\'s central store and are symlinked into the worktrees. Do not commit them.',
    '- `notes/` holds this WorkDesk\'s notes (markdown). Write findings, decisions and open questions there: they are kept in the Status Repo when the WorkDesk is cleared.',
    '- Do not start dev servers or terminals for other WorkDesks; each WorkDesk owns its terminals.',
    END
  )
  return lines.join('\n') + '\n'
}

/** Put the generated block into an existing file: replace it, or add it on top; the user's text is never touched. */
export function mergeGuide(existing: string | undefined, block: string): string {
  if (existing === undefined || existing.trim() === '') return `${block}\n${OWN_HEADING}\n\n${OWN_HINT}\n`
  const a = existing.indexOf(START)
  const b = existing.indexOf(END)
  if (a !== -1 && b > a) return existing.slice(0, a) + block.trimEnd() + existing.slice(b + END.length)
  return `${block}\n${existing}`
}

/** What the user wrote around the generated block (nothing, if they left the template alone). */
export function ownText(content: string): string {
  const b = content.indexOf(END)
  const rest = (b === -1 ? content : content.slice(b + END.length)).replace(OWN_HEADING, '').replace(OWN_HINT, '').trim()
  return rest
}

/** Write `<desk>/CLAUDE.md`: only if the WorkDesk folder exists (it is never created here), and only when something changed. */
export async function writeDeskGuide(root: string, desk: WorkDesk, todos: readonly Todo[]): Promise<void> {
  const dir = deskDir(root, desk.id)
  const file = join(dir, GUIDE_FILE)
  let existing: string | undefined
  try {
    existing = await readFile(file, 'utf8')
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err
    // no folder (a cleared WorkDesk, a review that checked nothing out yet): the file comes with the folder
    if (!existsSync(dir)) return
  }
  const next = mergeGuide(existing, renderGuide(desk, todos, dir))
  if (next !== existing) await writeFile(file, next)
}

/** The user's own text from the file, for the archive when the WorkDesk is cleared. */
export async function readOwnText(root: string, deskId: string): Promise<string> {
  try {
    return ownText(await readFile(join(deskDir(root, deskId), GUIDE_FILE), 'utf8'))
  } catch {
    return ''
  }
}
